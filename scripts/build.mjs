import { build } from "esbuild";
import { mkdir } from "node:fs/promises";
import { readFileSync } from "node:fs";
const { version } = JSON.parse(readFileSync("package.json", "utf8"));

await mkdir("dist", { recursive: true });
await build({
  entryPoints: ["src/index.ts"],
  outfile: "dist/pinned-playlist-plus.js",
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "chrome108",
  legalComments: "none",
  banner: {
    js: `/* Pinned Playlist Plus v${version} - generated from src/. Run npm run build; do not edit this file. */`,
  },
});
// Tests exercise the same typed modules without starting the browser extension.
await mkdir(".test-build", { recursive: true });
await build({
  entryPoints: ["src/public.ts"],
  outfile: ".test-build/extension.cjs",
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node24",
});
